// Builds compact lookup tables (time zones + places) from Google libphonenumber
// resources (Apache 2.0) downloaded into data-src/.
// Output: src/data/tz.js and src/data/geo.js
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(root, 'data-src');
const OUT = path.join(root, 'src/data');
fs.mkdirSync(OUT, { recursive: true });

const readMap = (file) => {
  const map = new Map();
  for (const line of fs.readFileSync(file, 'utf8').split('\n')) {
    if (!line || line.startsWith('#')) continue;
    const i = line.indexOf('|');
    if (i < 0) continue;
    map.set(line.slice(0, i), line.slice(i + 1).trim());
  }
  return map;
};

// ---------------------------------------------------------------- time zones
// map_data.txt dates from 2018 and sometimes uses a "same offset" proxy zone
// (e.g. Morocco -> Atlantic/Canary, Algeria -> Europe/Paris), which is wrong
// whenever daylight saving differs. We check every zone against the country's
// official zones (Intl.Locale#getTimeZones) and replace the proxies.
const { getCountries, getCountryCallingCode } = await import('libphonenumber-js/max');
const byCc = {};
for (const c of getCountries()) (byCc[getCountryCallingCode(c)] ??= []).push(c);
const zonesOfCountry = (c) => {
  try { const l = new Intl.Locale('und-' + c); return l.getTimeZones?.() || l.timeZones || []; } catch { return []; }
};
const canon = (z) => { try { return new Intl.DateTimeFormat('en', { timeZone: z }).resolvedOptions().timeZone; } catch { return null; } };
const tzMap = readMap(path.join(SRC, 'timezones/map_data.txt'));
const zones = [];
const zoneIdx = new Map();
const bad = new Set();
const fixed = [];
const tzEntries = [];
const zid = (z) => {
  if (!zoneIdx.has(z)) { zoneIdx.set(z, zones.length); zones.push(z); }
  return zoneIdx.get(z).toString(36);
};
for (const [prefix, value] of tzMap) {
  let list = value.split('&').filter((z) => (canon(z) ? true : (bad.add(z), false)));
  if (!prefix.startsWith('1')) {
    let cc = null;
    for (const L of [1, 2, 3]) if (byCc[prefix.slice(0, L)]) { cc = prefix.slice(0, L); break; }
    const allowed = new Set((byCc[cc] || []).flatMap(zonesOfCountry));
    if (allowed.size) {
      const ok = list.filter((z) => allowed.has(z) || allowed.has(canon(z)));
      if (ok.length !== list.length) {
        let repl = ok;
        if (cc === '7' && list.includes('Europe/Bucharest')) repl = [...ok, 'Europe/Kaliningrad'];
        if (!repl.length) repl = [...allowed];
        fixed.push(`${prefix}: ${list.join(',')} -> ${repl.join(',')}`);
        list = repl;
      }
    }
  }
  if (list.length) tzEntries.push(`${prefix}:${list.map(zid).join(',')}`);
}
// Countries spanning several time zones whose mobile numbers are not tied to a region
const MOBILE_ZONES = {};
for (const c of ['AU', 'RU', 'ID', 'KZ', 'CD', 'MN']) {
  MOBILE_ZONES[c] = zonesOfCountry(c).map(zid).join(',');
}
console.log('time zone fixes:\n  ' + fixed.join('\n  '));
if (bad.size) console.warn('Unknown zones skipped:', [...bad]);
fs.writeFileSync(
  path.join(OUT, 'tz.js'),
  `// Generated by scripts/build-data.mjs from libphonenumber timezones/map_data.txt (Apache 2.0)\n` +
  `export const ZONES = ${JSON.stringify(zones.join('|'))};\n` +
  `export const TZ = ${JSON.stringify(tzEntries.join('|'))};\n` +
  `export const MOBILE_ZONES = ${JSON.stringify(MOBILE_ZONES)};\n`
);

