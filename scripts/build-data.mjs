// Other countries: generic reduction with a size budget per country.
const KEY = new Set(['32', '41', '352', '44', '34', '351', '39', '49', '212', '213', '216', '61', '55', '52', '7', '31', '972', '971', '27', '64', '54', '56', '57', '90', '30', '353', '43', '45', '46', '47', '48', '420', '36', '40', '86', '91', '81', '65', '66', '84', '62', '63', '60']);
const reduce = (entries, L) => {
  const kept = new Map();
  const groups = new Map();
  for (const [p, v] of entries) {
    if (p.length <= L) kept.set(p, v);
    else {
      const g = p.slice(0, L);
      if (!groups.has(g)) groups.set(g, []);
      groups.get(g).push(v);
    }
  }
  for (const [g, vals] of groups) {
    if (kept.has(g)) continue;
    const uniq = [...new Set(vals)];
    if (uniq.length === 1) kept.set(g, uniq[0]);
    else {
      // common ", Region" suffix (e.g. "Guangzhou, Guangdong" / "Shenzhen, Guangdong")
      const suf = [...new Set(vals.map((v) => (v.includes(', ') ? v.split(', ').pop() : null)))];
      if (suf.length === 1 && suf[0]) kept.set(g, suf[0]);
    }
  }
  // prune entries equal to their nearest ancestor
  const keys = [...kept.keys()].sort((a, b) => a.length - b.length);
  for (const k of keys) {
    for (let i = k.length - 1; i > 0; i--) {
      const a = k.slice(0, i);
      if (kept.has(a)) { if (kept.get(a) === kept.get(k)) kept.delete(k); break; }
    }
  }
  return kept;
};
const files = fs.readdirSync(path.join(SRC, 'geo/en')).filter((f) => f.endsWith('.txt'));
let stats = [];
for (const f of files) {
  const cc = f.replace('.txt', '');
  if (cc === '1') continue;
  const frFile = path.join(SRC, 'geo/fr', f);
  const m = readMap(fs.existsSync(frFile) ? frFile : path.join(SRC, 'geo/en', f));
  const entries = [...m];
  const budget = KEY.has(cc) ? 3000 : 500;
  let best = null;
  for (let L = cc.length + 1; L <= 12; L++) {
    const r = reduce(entries, L);
    const size = [...r].reduce((s, [k, v]) => s + k.length + v.length + 2, 0);
    if (size > budget && best) break;
    best = r;
    if (size > budget) break; // even shortest is too big: keep it anyway
  }
  for (const [k, v] of best) geo.set(k, v);
  stats.push([cc, best.size]);
}
// Hand-written coarse regions where the generic reduction leaves gaps
